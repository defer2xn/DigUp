def quote(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def write(path, table):
    with open(path, "w", encoding="utf-8") as f:
        for key in sorted(table):
            f.write(f"{quote(key)} = {quote(table[key])};\n")


def main():
    keys = set()
    for name in glob.glob(os.path.join(sys.argv[1], "*.stringsdata")):
        for entries in json.load(open(name)).get("tables", {}).values():
            keys.update(e["key"] for e in entries)
    missing = sorted(k for k in keys if k not in ZH and k not in SAME)
    unused = sorted(k for k in ZH if k not in keys)
    root = os.path.join(os.path.dirname(__file__), "..", "Resources", "zh-Hans.lproj")
    write(os.path.join(root, "Localizable.strings"), {k: ZH[k] for k in keys if k in ZH})
    write(os.path.join(root, "InfoPlist.strings"), INFO_PLIST)
    print(f"{len(keys)} keys, {len(keys) - len(missing) - len(SAME & keys)} translated")
    for k in missing:
        print("missing:", json.dumps(k, ensure_ascii=False))
    for k in unused:
        print("unused:", json.dumps(k, ensure_ascii=False))
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
